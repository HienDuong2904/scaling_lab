-- Chat dataset (Project 7).
--   make seed-messages               (1M messages in 500 rooms)   make seed-messages rows=10000000
-- Each room's messages carry an increasing per-room seq, the ID clients send on reconnect.
-- Drops and recreates rooms and messages.

\set ON_ERROR_STOP on
\if :{?rows} \else \set rows 1000000 \endif
\if :{?rooms} \else \set rooms 500 \endif
\timing on

SELECT setseed(0.42);
DROP TABLE IF EXISTS messages, rooms CASCADE;

CREATE TABLE rooms (
  id         int PRIMARY KEY,
  tenant_id  int NOT NULL,
  name       text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO rooms (id, tenant_id, name)
SELECT r, 1 + (r % 20), 'room-' || r FROM generate_series(1, :rooms) r;

CREATE TABLE messages (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id    int NOT NULL,
  seq        bigint NOT NULL,
  user_id    int NOT NULL,
  body       text NOT NULL,
  created_at timestamptz NOT NULL
);

INSERT INTO messages (room_id, seq, user_id, body, created_at)
SELECT room_id,
       row_number() OVER (PARTITION BY room_id ORDER BY created_at),
       user_id, body, created_at
FROM (
  SELECT 1 + floor(power(random(), 2) * :rooms)::int AS room_id, -- some rooms much busier
         1 + floor(random() * 5000)::int AS user_id,
         (ARRAY['ok', 'on it', 'deploy is green', 'can you review?', 'p99 is up again', 'lgtm', 'rolling back', 'who owns this alert?'])[1 + floor(random() * 8)::int]
           || ' #' || m AS body,
         now() - random() * interval '90 days' AS created_at
  FROM generate_series(1, :rows) m
) s;

VACUUM (ANALYZE) rooms, messages;
SELECT count(*) AS messages, pg_size_pretty(pg_total_relation_size('messages')) AS size FROM messages;
