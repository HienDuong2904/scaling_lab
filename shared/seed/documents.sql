-- RAG dataset (Project 10): documents and chunks with random embeddings.
--   make seed-documents                       (10k documents x 10 chunks = 100k vectors)
--   make seed-documents rows=1000000 chunks=10   (10M vectors, the Project 10 break test; slow)
-- Embeddings are random unit vectors with the fake partner's default dimension (384), so they
-- test search speed and filtering, not answer quality. No vector index: that is a Project 10 fix.
-- Drops and recreates documents and chunks.

\set ON_ERROR_STOP on
\if :{?rows} \else \set rows 10000 \endif
\if :{?chunks} \else \set chunks 10 \endif
\if :{?dims} \else \set dims 384 \endif
\timing on

SELECT setseed(0.42);
DROP TABLE IF EXISTS chunks, documents CASCADE;

CREATE TABLE documents (
  id           bigint PRIMARY KEY,
  tenant_id    int NOT NULL,
  title        text NOT NULL,
  content_hash text NOT NULL,
  status       text NOT NULL DEFAULT 'ready',
  created_at   timestamptz NOT NULL
);

-- 5 tenants, tenant 1 holds 60% of documents (the big tenant), tenant 5 only 2%.
INSERT INTO documents
SELECT d,
       CASE WHEN r < 0.60 THEN 1 WHEN r < 0.80 THEN 2 WHEN r < 0.92 THEN 3 WHEN r < 0.98 THEN 4 ELSE 5 END,
       'Document ' || d,
       md5(d::text),
       'ready',
       now() - random() * interval '1 year'
FROM (SELECT d, random() AS r FROM generate_series(1, :rows) d) s;

CREATE TABLE chunks (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id     bigint NOT NULL,
  tenant_id       int NOT NULL,
  ordinal         int NOT NULL,
  content         text NOT NULL,
  embedding_model text NOT NULL,
  embedding       vector(:dims) NOT NULL
);

INSERT INTO chunks (document_id, tenant_id, ordinal, content, embedding_model, embedding)
SELECT d.id, d.tenant_id, k,
       'Chunk ' || k || ' of document ' || d.id || ': synthetic text about orders, queues and caches.',
       'embed-small',
       (SELECT array_agg(random() * 2 - 1) FROM generate_series(1, :dims) WHERE d.id > 0 AND k > 0)::vector
FROM documents d, generate_series(1, :chunks) k;

VACUUM (ANALYZE) documents, chunks;
SELECT count(*) AS chunks, pg_size_pretty(pg_total_relation_size('chunks')) AS size FROM chunks;
SELECT tenant_id, count(*) AS chunks FROM chunks GROUP BY tenant_id ORDER BY tenant_id;
